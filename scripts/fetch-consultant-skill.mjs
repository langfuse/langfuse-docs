/**
 * Bake consultant.md from the pinned skills commit into a TypeScript module.
 * Fails the process on any fetch or parse error so a bad pin cannot ship.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import {
  CONSULTANT_SKILL_PIN,
  consultantSkillRawUrl,
} from "../lib/consultant/pin.mjs";
import { parseConsultantSkill } from "../lib/consultant/parse-skill.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "lib/consultant/skill.generated.ts");
const url = consultantSkillRawUrl();

const response = await fetch(url, {
  headers: {
    Accept: "text/plain, text/markdown;q=0.9",
    "User-Agent": "langfuse-docs-consultant-pin",
  },
  redirect: "error",
  signal: AbortSignal.timeout(20_000),
});

if (!response.ok) {
  throw new Error(
    `Failed to fetch consultant skill (${response.status}) from ${url}`,
  );
}

const markdown = await response.text();
if (
  markdown.trimStart().startsWith("<!DOCTYPE") ||
  markdown.includes("<html")
) {
  throw new Error(
    `Consultant skill URL returned HTML instead of markdown: ${url}`,
  );
}

const skill = parseConsultantSkill(markdown, CONSULTANT_SKILL_PIN.name);
const pin = {
  owner: CONSULTANT_SKILL_PIN.owner,
  repo: CONSULTANT_SKILL_PIN.repo,
  branch: CONSULTANT_SKILL_PIN.branch,
  sha: CONSULTANT_SKILL_PIN.sha,
  path: CONSULTANT_SKILL_PIN.path,
  url,
};

const source = `// Generated by scripts/fetch-consultant-skill.mjs. Do not edit.
// Pin ${pin.sha} on ${pin.branch}. When langfuse-consultant is on skills main,
// update lib/consultant/pin.mjs and run this script again.

export const consultantSkillPin = ${JSON.stringify(pin, null, 2)} as const;

export const consultantSkillSource = ${JSON.stringify(skill, null, 2)} as const;
`;

fs.writeFileSync(outputPath, source);
execFileSync(
  "pnpm",
  ["exec", "prettier", "--write", "lib/consultant/skill.generated.ts"],
  { cwd: root, stdio: "inherit" },
);

const written = fs.readFileSync(outputPath, "utf8");
if (!written.includes(pin.sha) || !written.includes(skill.name)) {
  throw new Error("Generated consultant skill module is missing the pin");
}

console.log(
  `Baked ${skill.name} from ${pin.sha.slice(0, 12)} into ${outputPath}`,
);

/**
 * Bake the consultant playbook and every pinned Langfuse skill into a
 * TypeScript module. Fails on a parse error so a bad pin cannot ship. If
 * GitHub cannot be reached and the committed module already matches the pin,
 * that module is kept.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import {
  CONSULTANT_SKILL_PIN,
  consultantSkillTarballUrl,
} from "../lib/consultant/pin.mjs";
import { collectSkills, readTarGz } from "../lib/consultant/skill-bundle.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "lib/consultant/skill.generated.ts");
const url = consultantSkillTarballUrl();

async function download() {
  const response = await fetch(url, {
    headers: { "User-Agent": "langfuse-docs-consultant-pin" },
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch skills (${response.status}) from ${url}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

let archive;
try {
  archive = await download();
} catch (error) {
  const existing = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, "utf8")
    : "";
  if (
    existing.includes(`sha: "${CONSULTANT_SKILL_PIN.sha}"`) &&
    existing.includes("consultantAllSkillSources")
  ) {
    console.warn(
      `Could not download skills (${error instanceof Error ? error.message : error}). Keeping the committed module for ${CONSULTANT_SKILL_PIN.sha.slice(0, 12)}.`,
    );
    process.exit(0);
  }
  throw error;
}

const { consultant, skills } = collectSkills(readTarGz(archive), {
  root: CONSULTANT_SKILL_PIN.skillsRoot,
  consultantPath: CONSULTANT_SKILL_PIN.path,
  consultantName: CONSULTANT_SKILL_PIN.name,
});
const pin = {
  owner: CONSULTANT_SKILL_PIN.owner,
  repo: CONSULTANT_SKILL_PIN.repo,
  branch: CONSULTANT_SKILL_PIN.branch,
  sha: CONSULTANT_SKILL_PIN.sha,
  path: CONSULTANT_SKILL_PIN.path,
  url,
};

const source = `// Generated by scripts/fetch-consultant-skill.mjs. Do not edit.
// Pin ${pin.sha} on ${pin.branch}. When langfuse-consultant is on skills main,
// update lib/consultant/pin.mjs and run this script again.

export const consultantSkillPin = ${JSON.stringify(pin, null, 2)} as const;

export const consultantSkillSource = ${JSON.stringify(consultant, null, 2)} as const;

export const consultantAllSkillSources = ${JSON.stringify(skills, null, 2)} as const;
`;

fs.writeFileSync(outputPath, source);
execFileSync(
  "pnpm",
  ["exec", "prettier", "--write", "lib/consultant/skill.generated.ts"],
  { cwd: root, stdio: "inherit" },
);

const written = fs.readFileSync(outputPath, "utf8");
if (!written.includes(pin.sha) || !written.includes(consultant.name)) {
  throw new Error("Generated consultant skill module is missing the pin");
}

const referenceCount = skills.reduce(
  (count, skill) => count + Object.keys(skill.references).length,
  0,
);
console.log(
  `Baked ${consultant.name} and ${skills.map((skill) => skill.name).join(", ")} (${referenceCount} references) from ${pin.sha.slice(0, 12)} into ${outputPath}`,
);
